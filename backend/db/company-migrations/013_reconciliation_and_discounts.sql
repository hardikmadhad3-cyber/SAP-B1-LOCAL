-- Phase 4 finance: cash discount accounts, internal reconciliation and tax on
-- manual journal entry rows.

-- G/L Account Determination: cash discount granted to customers (expense) and
-- taken from vendors (income). Local column names; SAP keeps these in its
-- account determination tables.
ALTER TABLE "OACP"
  ADD COLUMN IF NOT EXISTS "CashDscAR" TEXT REFERENCES "OACT"("AcctCode"),
  ADD COLUMN IF NOT EXISTS "CashDscAP" TEXT REFERENCES "OACT"("AcctCode");

-- SDK OITR / ITR1: internal reconciliations of a business partner's open journal rows.
CREATE TABLE IF NOT EXISTS "OITR" (
  "ReconNum" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ReconDate" DATE NOT NULL, "IsCard" CHAR(1) DEFAULT 'C' CHECK ("IsCard" IN ('C','A')),
  "CardOrAcct" TEXT NOT NULL, "ReconType" INTEGER DEFAULT 0, "Total" NUMERIC(19,6) DEFAULT 0,
  "Canceled" CHAR(1) DEFAULT 'N' CHECK ("Canceled" IN ('Y','N')), "CreateDate" DATE DEFAULT CURRENT_DATE, "UserSign" INTEGER
);
CREATE TABLE IF NOT EXISTS "ITR1" (
  "ReconNum" INTEGER NOT NULL REFERENCES "OITR"("ReconNum"), "LineSeq" INTEGER NOT NULL,
  "ShortName" TEXT, "Account" TEXT REFERENCES "OACT"("AcctCode"), "TransId" INTEGER NOT NULL, "TransRowId" INTEGER NOT NULL,
  "SrcObjTyp" TEXT, "SrcObjAbs" INTEGER, "ReconSum" NUMERIC(19,6) DEFAULT 0, "IsCredit" CHAR(1) CHECK ("IsCredit" IN ('D','C')),
  PRIMARY KEY ("ReconNum", "LineSeq"),
  FOREIGN KEY ("TransId", "TransRowId") REFERENCES "JDT1"("TransId", "Line_ID")
);
CREATE INDEX IF NOT EXISTS "IX_ITR1_Row" ON "ITR1" ("TransId", "TransRowId");

-- SDK JDT1 tax columns: tax code and base on the taxed row, tax rows flagged VatLine.
ALTER TABLE "JDT1"
  ADD COLUMN IF NOT EXISTS "VatGroup" TEXT, ADD COLUMN IF NOT EXISTS "BaseSum" NUMERIC(19,6) DEFAULT 0,
  ADD COLUMN IF NOT EXISTS "VatAmount" NUMERIC(19,6) DEFAULT 0, ADD COLUMN IF NOT EXISTS "VatLine" CHAR(1) DEFAULT 'N';

-- Opening balances post against the starter chart's Opening Balance Equity account
-- unless the company already chose its own.
UPDATE "OACP" SET "LinkAct_18" = COALESCE("LinkAct_18", '300000'), "DftStockOB" = COALESCE("DftStockOB", '300000')
 WHERE EXISTS (SELECT 1 FROM "OACT" WHERE "AcctCode" = '300000');
