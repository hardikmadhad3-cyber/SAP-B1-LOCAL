-- Phase 4 payments: Incoming Payments (ORCT, object 24) and Outgoing Payments
-- (OVPM, object 46) with their SDK child tables, and the invoice columns the
-- payment pages' open-item lists read.

-- SDK ORCT/OVPM header columns (OVPM was created LIKE ORCT, so both get them).
ALTER TABLE "ORCT"
  ADD COLUMN IF NOT EXISTS "DocType" CHAR(1) DEFAULT 'C' CHECK ("DocType" IN ('C','S','A')),
  ADD COLUMN IF NOT EXISTS "ObjType" TEXT DEFAULT '24',
  ADD COLUMN IF NOT EXISTS "DocDueDate" DATE,
  ADD COLUMN IF NOT EXISTS "TrsfrDate" DATE,
  ADD COLUMN IF NOT EXISTS "TrsfrRef" TEXT,
  ADD COLUMN IF NOT EXISTS "CheckAcct" TEXT,
  ADD COLUMN IF NOT EXISTS "CheckSum" NUMERIC(19,6) DEFAULT 0,
  ADD COLUMN IF NOT EXISTS "CreditSum" NUMERIC(19,6) DEFAULT 0,
  ADD COLUMN IF NOT EXISTS "BpAct" TEXT,
  ADD COLUMN IF NOT EXISTS "PayNoDoc" CHAR(1) DEFAULT 'N',
  ADD COLUMN IF NOT EXISTS "CreateDate" DATE DEFAULT CURRENT_DATE;
ALTER TABLE "OVPM"
  ADD COLUMN IF NOT EXISTS "DocType" CHAR(1) DEFAULT 'S' CHECK ("DocType" IN ('C','S','A')),
  ADD COLUMN IF NOT EXISTS "ObjType" TEXT DEFAULT '46',
  ADD COLUMN IF NOT EXISTS "DocDueDate" DATE,
  ADD COLUMN IF NOT EXISTS "TrsfrDate" DATE,
  ADD COLUMN IF NOT EXISTS "TrsfrRef" TEXT,
  ADD COLUMN IF NOT EXISTS "CheckAcct" TEXT,
  ADD COLUMN IF NOT EXISTS "CheckSum" NUMERIC(19,6) DEFAULT 0,
  ADD COLUMN IF NOT EXISTS "CreditSum" NUMERIC(19,6) DEFAULT 0,
  ADD COLUMN IF NOT EXISTS "BpAct" TEXT,
  ADD COLUMN IF NOT EXISTS "PayNoDoc" CHAR(1) DEFAULT 'N',
  ADD COLUMN IF NOT EXISTS "CreateDate" DATE DEFAULT CURRENT_DATE;

-- RCT1/VPM1 checks, RCT2/VPM2 paid documents, RCT3/VPM3 credit cards, RCT4/VPM4 G/L accounts.
CREATE TABLE IF NOT EXISTS "RCT1" (
  "DocNum" INTEGER NOT NULL REFERENCES "ORCT"("DocEntry"), "LineID" INTEGER NOT NULL,
  "DueDate" DATE, "CheckNum" INTEGER, "BankCode" TEXT, "CountryCod" TEXT, "CheckSum" NUMERIC(19,6) DEFAULT 0,
  "CheckAct" TEXT REFERENCES "OACT"("AcctCode"), PRIMARY KEY ("DocNum", "LineID"));
CREATE TABLE IF NOT EXISTS "RCT2" (
  "DocNum" INTEGER NOT NULL REFERENCES "ORCT"("DocEntry"), "InvoiceId" INTEGER NOT NULL,
  "DocEntry" INTEGER NOT NULL, "InvType" INTEGER NOT NULL, "InstId" INTEGER DEFAULT 1, "DocLine" INTEGER,
  "SumApplied" NUMERIC(19,6) DEFAULT 0, "DcntSum" NUMERIC(19,6) DEFAULT 0, "OcrCode" TEXT,
  PRIMARY KEY ("DocNum", "InvoiceId"));
CREATE TABLE IF NOT EXISTS "RCT3" (
  "DocNum" INTEGER NOT NULL REFERENCES "ORCT"("DocEntry"), "LineID" INTEGER NOT NULL,
  "CreditCard" INTEGER, "CreditAcct" TEXT REFERENCES "OACT"("AcctCode"), "CrCardNum" TEXT, "CardValid" DATE,
  "VoucherNum" TEXT, "OwnerIdNum" TEXT, "OwnerPhone" TEXT, "NumOfPmnts" INTEGER DEFAULT 1,
  "CreditSum" NUMERIC(19,6) DEFAULT 0, PRIMARY KEY ("DocNum", "LineID"));
CREATE TABLE IF NOT EXISTS "RCT4" (
  "DocNum" INTEGER NOT NULL REFERENCES "ORCT"("DocEntry"), "LineId" INTEGER NOT NULL,
  "AcctCode" TEXT NOT NULL REFERENCES "OACT"("AcctCode"), "SumApplied" NUMERIC(19,6) DEFAULT 0,
  "Descrip" TEXT, "OcrCode" TEXT, "LocCode" INTEGER, "Project" TEXT, PRIMARY KEY ("DocNum", "LineId"));
CREATE TABLE IF NOT EXISTS "VPM1" (LIKE "RCT1" INCLUDING ALL);
CREATE TABLE IF NOT EXISTS "VPM2" (LIKE "RCT2" INCLUDING ALL);
CREATE TABLE IF NOT EXISTS "VPM3" (LIKE "RCT3" INCLUDING ALL);
CREATE TABLE IF NOT EXISTS "VPM4" (LIKE "RCT4" INCLUDING ALL);
ALTER TABLE "VPM1" ADD FOREIGN KEY ("DocNum") REFERENCES "OVPM"("DocEntry"), ADD FOREIGN KEY ("CheckAct") REFERENCES "OACT"("AcctCode");
ALTER TABLE "VPM2" ADD FOREIGN KEY ("DocNum") REFERENCES "OVPM"("DocEntry");
ALTER TABLE "VPM3" ADD FOREIGN KEY ("DocNum") REFERENCES "OVPM"("DocEntry"), ADD FOREIGN KEY ("CreditAcct") REFERENCES "OACT"("AcctCode");
ALTER TABLE "VPM4" ADD FOREIGN KEY ("DocNum") REFERENCES "OVPM"("DocEntry"), ADD FOREIGN KEY ("AcctCode") REFERENCES "OACT"("AcctCode");
CREATE INDEX IF NOT EXISTS "IX_RCT2_Doc" ON "RCT2" ("InvType", "DocEntry");
CREATE INDEX IF NOT EXISTS "IX_VPM2_Doc" ON "VPM2" ("InvType", "DocEntry");

-- SDK invoice columns read by the payment pages (control account, payment reference, project).
ALTER TABLE "OINV" ADD COLUMN IF NOT EXISTS "CtlAccount" TEXT, ADD COLUMN IF NOT EXISTS "PaymentRef" TEXT, ADD COLUMN IF NOT EXISTS "Project" TEXT;
ALTER TABLE "ORIN" ADD COLUMN IF NOT EXISTS "CtlAccount" TEXT, ADD COLUMN IF NOT EXISTS "PaymentRef" TEXT, ADD COLUMN IF NOT EXISTS "Project" TEXT;
ALTER TABLE "OPCH" ADD COLUMN IF NOT EXISTS "CtlAccount" TEXT, ADD COLUMN IF NOT EXISTS "PaymentRef" TEXT, ADD COLUMN IF NOT EXISTS "Project" TEXT;
ALTER TABLE "ORPC" ADD COLUMN IF NOT EXISTS "CtlAccount" TEXT, ADD COLUMN IF NOT EXISTS "PaymentRef" TEXT, ADD COLUMN IF NOT EXISTS "Project" TEXT;
-- Journal rows of a business partner are looked up by BP for open items.
CREATE INDEX IF NOT EXISTS "IX_JDT1_ShortName" ON "JDT1" ("ShortName");
