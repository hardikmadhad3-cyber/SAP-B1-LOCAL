// Generates services/localItemFields.js from itemDbService.mapHeaderRow (the
// reader the Item Master page uses), so the local Items writer and the reader
// never disagree. Run after changing mapHeaderRow:
//   node scripts/generateLocalItemFields.js
const fs = require('fs');
const path = require('path');
const B = path.join(__dirname, '..');
const src = fs.readFileSync(`${B}/services/itemDbService.js`, 'utf8');

// Enum maps from the mapX helpers: { mapItemType: { I: 'itItems', ... } }
const enums = {};
for (const m of src.matchAll(/const (map\w+) = \(value\) => \{\s*const map = \{([\s\S]*?)\};/g)) {
  const entries = [...m[2].matchAll(/['"]?(\w+)['"]?\s*:\s*'(\w+)'/g)].map((e) => [e[1], e[2]]);
  enums[m[1]] = Object.fromEntries(entries);
}

const block = src.slice(src.indexOf('const mapHeaderRow'), src.indexOf('for (let i = 1; i <= 64'));
// Join-derived names and quantities/costs SAP maintains itself: never written by the page.
const READ_ONLY = new Set(['OnHand', 'IsCommited', 'OnOrder', 'AvgPrice', 'LstEvlPric', 'LastPurPrc', 'CreateDate', 'UpdateDate']);
const SKIP_PROPS = new Set(['ItemsGroupName', 'ManufacturerName', 'DefaultVendorName', 'UoMGroupName', 'Remarks', 'AvgStdPrice',
  'QuantityOnStock', 'QuantityOrderedFromVendors', 'QuantityOrderedByCustomers', 'MovingAveragePrice', 'LastPurPrc']);

const fields = {};
const kinds = {};
const enumFields = {};
for (const line of block.split('\n')) {
  const m = line.match(/^\s+(\w+):\s*(.+?),?\s*$/);
  if (!m || SKIP_PROPS.has(m[1])) continue;
  const [, prop, expr] = m;
  let col; let kind;
  if (prop === 'ChapterID') { col = 'ChapterID'; kind = 'int'; }
  else {
    const fn = expr.match(/^(\w+)\(row\.(\w+)/);
    const plain = expr.match(/^row\.(\w+)\s*\|\|/);
    if (fn) {
      col = fn[2];
      kind = { toSapBool: 'bool', toNumberOrBlank: 'num', toIntOrDefault: 'int', toIsoDate: 'date' }[fn[1]];
      if (!kind && enums[fn[1]]) { kind = 'enum'; enumFields[prop] = enums[fn[1]]; }
      if (!kind) throw new Error(`Unknown converter ${fn[1]} for ${prop}`);
    } else if (plain) { col = plain[1]; kind = 'text'; } else continue;
  }
  if (READ_ONLY.has(col)) continue;
  fields[prop] = col;
  kinds[col] = kind;
}
for (let i = 1; i <= 64; i += 1) { fields[`Properties${i}`] = `QryGroup${i}`; kinds[`QryGroup${i}`] = 'bool'; }

const out = `// GENERATED by scripts/generateLocalItemFields.js from itemDbService.mapHeaderRow. Do not edit.
// SL property -> OITM column; kinds drive value conversion; enums are SAP value -> SL value.
module.exports = ${JSON.stringify({ fields, kinds, enums: enumFields }, null, 2)};
`;
fs.writeFileSync(path.join(B, 'services', 'localItemFields.js'), out);
console.log(Object.keys(fields).length, 'fields;', Object.keys(enumFields).length, 'enums');
